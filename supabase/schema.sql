-- Basic server-side analytics abuse guard: same visitor key/event type cannot create more than
-- one event within the short client cooldown window. This is defense-in-depth; it is not an
-- identity system and does not expose visitor data publicly.
create or replace function public.guard_analytics_event() returns trigger language plpgsql security definer set search_path=public as $$
begin
  if new.visitor_key is not null and exists(select 1 from public.analytics_events e where e.visitor_key=new.visitor_key and e.event_type=new.event_type and e.created_at > now()-interval '1 second') then
    raise exception 'Analytics rate limit exceeded';
  end if;
  return new;
end; $$;
drop trigger if exists analytics_rate_guard on public.analytics_events;
create trigger analytics_rate_guard before insert on public.analytics_events for each row execute function public.guard_analytics_event();
revoke all on function public.guard_analytics_event() from public;
