create or replace function public.restore_content_backup(p_backup jsonb) returns void language plpgsql security definer set search_path=public as $$
declare i jsonb; begin
 if not public.is_owner() then raise exception 'Owner permission required'; end if;
 if coalesce(p_backup->>'version','') not in ('3','4') then raise exception 'Unsupported backup version'; end if;
 if jsonb_typeof(p_backup->'jobs')<>'array' or jsonb_typeof(p_backup->'exams')<>'array' or jsonb_typeof(p_backup->'results')<>'array' or jsonb_typeof(p_backup->'admitCards')<>'array' or jsonb_typeof(p_backup->'blog')<>'array' then raise exception 'Invalid backup collections'; end if;
 for i in select * from jsonb_array_elements(p_backup->'jobs') loop if coalesce(i->>'id','')='' then raise exception 'Invalid job id'; end if; end loop;
 for i in select * from jsonb_array_elements(p_backup->'exams') loop if coalesce(i->>'id','')='' then raise exception 'Invalid exam id'; end if; end loop;
 for i in select * from jsonb_array_elements(p_backup->'results') loop if coalesce(i->>'id','')='' then raise exception 'Invalid result id'; end if; end loop;
 for i in select * from jsonb_array_elements(p_backup->'admitCards') loop if coalesce(i->>'id','')='' then raise exception 'Invalid admit card id'; end if; end loop;
 for i in select * from jsonb_array_elements(p_backup->'blog') loop if coalesce(i->>'id','')='' then raise exception 'Invalid blog id'; end if; end loop;
 if p_backup ? 'adSlots' and jsonb_typeof(p_backup->'adSlots')<>'array' then raise exception 'Invalid adSlots'; end if;
 if exists(select 1 from (select i->>'id' id, count(*) c from jsonb_array_elements(p_backup->'jobs') i group by 1 having count(*)>1) q) then raise exception 'Duplicate job IDs in backup'; end if;
 if exists(select 1 from (select i->>'slug' slug, count(*) c from jsonb_array_elements(p_backup->'jobs') i where coalesce(i->>'slug','')<>'' group by 1 having count(*)>1) q) then raise exception 'Duplicate job slugs in backup'; end if;
 if exists(select 1 from (select i->>'slug' slug, count(*) c from jsonb_array_elements(p_backup->'blog') i where coalesce(i->>'slug','')<>'' group by 1 having count(*)>1) q) then raise exception 'Duplicate blog slugs in backup'; end if;
 if p_backup ? 'settings' and jsonb_typeof(p_backup->'settings')<>'object' then raise exception 'Invalid settings object'; end if;
 if p_backup ? 'features' and jsonb_typeof(p_backup->'features')<>'object' then raise exception 'Invalid features object'; end if;
 if p_backup ? 'adSlots' then
   for i in select * from jsonb_array_elements(p_backup->'adSlots') loop
     if coalesce(i->>'id','')='' or coalesce(i->>'title','')='' or coalesce(i->>'locationName','')='' then raise exception 'Invalid ad slot'; end if;
   end loop;
 end if;
 delete from public.content_records;
 for i in select * from jsonb_array_elements(p_backup->'jobs') loop insert into public.content_records(kind,id,payload,published) values('jobs',i->>'id',i,coalesce((i->>'published')::boolean,false)); end loop;
 for i in select * from jsonb_array_elements(p_backup->'exams') loop insert into public.content_records(kind,id,payload,published) values('exams',i->>'id',i,coalesce((i->>'published')::boolean,false)); end loop;
 for i in select * from jsonb_array_elements(p_backup->'results') loop insert into public.content_records(kind,id,payload,published) values('results',i->>'id',i,coalesce((i->>'published')::boolean,false)); end loop;
 for i in select * from jsonb_array_elements(p_backup->'admitCards') loop insert into public.content_records(kind,id,payload,published) values('admit_cards',i->>'id',i,coalesce((i->>'published')::boolean,false)); end loop;
 for i in select * from jsonb_array_elements(p_backup->'blog') loop insert into public.content_records(kind,id,payload,published) values('blog',i->>'id',i,coalesce((i->>'published')::boolean,false)); end loop;
 if p_backup ? 'settings' then insert into public.site_config(key,value,updated_at) values('settings',p_backup->'settings',now()) on conflict(key) do update set value=excluded.value,updated_at=now(); end if;
 if p_backup ? 'features' then insert into public.site_config(key,value,updated_at) values('features',(p_backup->'features') - 'adminUsers',now()) on conflict(key) do update set value=excluded.value,updated_at=now(); end if;
 if p_backup ? 'adSlots' then
   delete from public.ad_slots;
   for i in select * from jsonb_array_elements(p_backup->'adSlots') loop insert into public.ad_slots(id,title,location_name,html_content,enabled,updated_at) values(i->>'id',i->>'title',i->>'locationName',coalesce(i->>'htmlContent',''),coalesce((i->>'enabled')::boolean,false),now()); end loop;
 end if;
end; $$;
revoke all on function public.restore_content_backup(jsonb) from public; grant execute on function public.restore_content_backup(jsonb) to authenticated;

create or replace function public.expire_due_jobs() returns integer language plpgsql security definer set search_path=public as $$
declare changed integer:=0; r record; d date; new_status text;
begin
 if not public.is_admin() then raise exception 'Admin permission required'; end if;
 for r in select id,payload,published from public.content_records where kind='jobs' loop
   begin d:=coalesce(nullif(r.payload->>'lastDateISO','')::date, nullif(r.payload->>'lastDate','')::date); exception when others then d:=null; end;
   if d is null then continue; end if;
   if d < current_date and r.published then update public.content_records set published=false,payload=jsonb_set(jsonb_set(payload,'{published}','false'::jsonb,true),'{status}','"Expired"'::jsonb,true),updated_at=now() where kind='jobs' and id=r.id; changed:=changed+1;
   elsif r.published and d <= current_date+7 and coalesce(r.payload->>'status','')<>'Closing Soon' then update public.content_records set payload=jsonb_set(payload,'{status}','"Closing Soon"'::jsonb,true),updated_at=now() where kind='jobs' and id=r.id; changed:=changed+1;
   elsif r.published and d > current_date+7 and coalesce(r.payload->>'status','')='Closing Soon' then update public.content_records set payload=jsonb_set(payload,'{status}','"Active"'::jsonb,true),updated_at=now() where kind='jobs' and id=r.id; changed:=changed+1;
   end if;
 end loop; return changed; end; $$;
revoke all on function public.expire_due_jobs() from public; grant execute on function public.expire_due_jobs() to authenticated;

