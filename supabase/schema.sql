create or replace function public.upsert_admin_by_email(p_email text,p_role text) returns void language plpgsql security definer set search_path=public,auth as $$
declare uid uuid; begin
 if not public.is_owner() then raise exception 'Owner permission required'; end if;
 if p_role not in ('owner','editor','viewer') then raise exception 'Invalid role'; end if;
 select id into uid from auth.users where lower(email)=lower(trim(p_email)) limit 1;
 if uid is null then raise exception 'No Supabase user exists for this email'; end if;
 if p_role='owner' and exists(select 1 from public.admin_users where role='owner' and user_id<>uid) then raise exception 'Only one owner is allowed'; end if;
 insert into public.admin_users(user_id,role) values(uid,p_role) on conflict(user_id) do update set role=excluded.role,updated_at=now();
end; $$;
revoke all on function public.upsert_admin_by_email(text,text) from public; grant execute on function public.upsert_admin_by_email(text,text) to authenticated;

create or replace function public.remove_admin_by_email(p_email text) returns void language plpgsql security definer set search_path=public,auth as $$
declare uid uuid; begin
 if not public.is_owner() then raise exception 'Owner permission required'; end if;
 select id into uid from auth.users where lower(email)=lower(trim(p_email)) limit 1;
 if uid is not null then if uid=auth.uid() then raise exception 'You cannot remove your own owner account'; end if; delete from public.admin_users where user_id=uid; end if;
end; $$;
revoke all on function public.remove_admin_by_email(text) from public; grant execute on function public.remove_admin_by_email(text) to authenticated;
