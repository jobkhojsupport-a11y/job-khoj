create or replace function public.validate_content_payload() returns trigger language plpgsql security definer set search_path=public as $$
begin
  if jsonb_typeof(new.payload) <> 'object' then raise exception 'Content payload must be a JSON object'; end if;
  if new.kind='jobs' then
    if coalesce(length(trim(new.payload->>'title')),0)=0 or coalesce(length(trim(new.payload->>'org')),0)=0 then raise exception 'Job title and organization are required'; end if;
    if new.payload ? 'category' and (new.payload->>'category') not in ('Government','Private','Bank','Railway','Teaching','Defence','Police','Apprentice') then raise exception 'Invalid job category'; end if;
    if new.payload ? 'jobType' and (new.payload->>'jobType') not in ('Permanent','Contractual','Apprentice','Full Time') then raise exception 'Invalid job type'; end if;
  elsif new.kind='exams' then
    if coalesce(length(trim(new.payload->>'examName')),0)=0 or coalesce(length(trim(new.payload->>'org')),0)=0 then raise exception 'Exam name and organization are required'; end if;
  elsif new.kind='results' then
    if coalesce(length(trim(new.payload->>'resultTitle')),0)=0 or coalesce(length(trim(new.payload->>'org')),0)=0 then raise exception 'Result title and organization are required'; end if;
  elsif new.kind='admit_cards' then
    if coalesce(length(trim(new.payload->>'examName')),0)=0 or coalesce(length(trim(new.payload->>'org')),0)=0 then raise exception 'Exam name and organization are required'; end if;
  elsif new.kind='blog' then
    if coalesce(length(trim(new.payload->>'title')),0)=0 or coalesce(length(trim(new.payload->>'content')),0)=0 then raise exception 'Blog title and content are required'; end if;
  end if;
  new.payload=jsonb_set(new.payload,'{published}',to_jsonb(new.published),true);
  return new;
end; $$;
drop trigger if exists content_payload_validate on public.content_records;
