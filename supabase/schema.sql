create or replace function public.record_analytics_event(p_event_type text,p_label text,p_visitor_key text) returns void language plpgsql security definer set search_path=public as $$
begin
  if p_event_type not in ('page_view','job_view','apply_click','whatsapp_click','search') then raise exception 'Invalid analytics event'; end if;
  if p_label is not null and length(p_label)>200 then raise exception 'Analytics label too long'; end if;
  if p_visitor_key is null or length(trim(p_visitor_key))<16 or length(p_visitor_key)>128 then raise exception 'Invalid analytics visitor key'; end if;
  if exists(select 1 from public.analytics_events where visitor_key=p_visitor_key and event_type=p_event_type and created_at>now()-interval '2 seconds') then return; end if;
  if (select count(*) from public.analytics_events where visitor_key=p_visitor_key and created_at>now()-interval '1 minute') >= 30 then return; end if;
  insert into public.analytics_events(event_type,label,visitor_key) values(p_event_type,nullif(trim(p_label),''),p_visitor_key);
end; $$;
revoke all on function public.record_analytics_event(text,text,text) from public; grant execute on function public.record_analytics_event(text,text,text) to anon,authenticated;


